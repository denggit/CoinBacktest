def run_self_test() -> None:
    index = pd.date_range("2024-01-01", periods=90, freq="1min")
    close = np.linspace(100.0, 102.0, len(index))
    bars = pd.DataFrame({"open": close, "high": close + 0.5, "low": close - 0.5, "close": close}, index=index)
    mask_high = pivot_mask(pd.Series([1, 2, 4, 2, 1], dtype=float), 1, high=True)
    mask_low = pivot_mask(pd.Series([4, 2, 1, 2, 4], dtype=float), 1, high=False)
    if not mask_high[2] or not mask_low[2]:
        raise AssertionError("symmetric pivot fixture failed")
    candidate = pd.DataFrame(
        [{
            "candidate_id": "fixture", "variant": "fixture", "year": 2024, "side": 1, "side_name": "LONG",
            "entry_limit": 101.0, "stop_price": 99.0, "risk_fraction": 2 / 101,
            "order_start_pos": 5, "order_start_time": index[5],
        }]
    )
    bars.loc[index[7], ["low", "high", "open", "close"]] = [100.5, 102.5, 101.2, 102.0]
    filled = attach_first_fills(candidate, bars, max_expiry=10)
    replay = replay_outcomes(filled, bars, expiries=(10,), targets=(1.0,), hold_minutes=20)
    if filled.loc[0, "first_fill_status"] != "FILLED" or replay.loc[0, "outcome"] != "TP":
        raise AssertionError("limit fill / TP fixture failed")
    print("[self-test] passed", flush=True)


def run(args: argparse.Namespace) -> Path:
    if args.self_test:
        run_self_test()
        return PROJECT_ROOT / args.out_dir
    bars = load_bars(args)
    research_start = pd.Timestamp(args.start_date)
    actual_end_exclusive = bars.index.max() + pd.Timedelta(minutes=1)
    if bars.index.min() > pd.Timestamp(args.warmup_start_date):
        raise RuntimeError("local data does not cover the requested warmup start")
    if actual_end_exclusive <= research_start:
        raise RuntimeError("no research-period bars returned by data_feed")
    print(f"[window] warmup={bars.index.min()} -> 2022-12-31; research={research_start} -> {bars.index.max()}", flush=True)

    levels_by_width: dict[int, pd.DataFrame] = {}
    for width in sorted({variant.macro_width for variant in VARIANTS}):
        levels = build_macro_levels(bars, width)
        if levels.empty:
            raise RuntimeError(f"no macro levels for width={width}")
        levels_by_width[width] = levels
        print(f"[levels] width={width} levels={len(levels):,}", flush=True)

    candidate_parts: list[pd.DataFrame] = []
    for variant in VARIANTS:
        print(f"[scan] {variant.name}", flush=True)
        part = scan_candidates(
            bars,
            levels_by_width[variant.macro_width],
            variant,
            research_start=research_start,
            research_end_exclusive=actual_end_exclusive,
        )
        print(f"[scan] {variant.name} candidates={len(part):,}", flush=True)
        if not part.empty:
            candidate_parts.append(part)
    candidates = pd.concat(candidate_parts, ignore_index=True) if candidate_parts else pd.DataFrame()
    if candidates.empty:
        raise RuntimeError("No causal sweep -> MSS -> FVG candidates. The requested pattern is not present under frozen definitions.")
    candidates["candidate_id"] = [f"{row.variant}_{idx:06d}" for idx, row in enumerate(candidates.itertuples(index=False))]
    print(f"[candidates] total={len(candidates):,}", flush=True)

    fills = attach_first_fills(candidates, bars, max(ORDER_EXPIRIES))
    outcomes = replay_outcomes(fills, bars)
    scorecard = build_scorecard(candidates, fills, outcomes)
    gates, selected, has_edge = select_edge(scorecard)
    print(f"[edge-gate] selected={selected} passed={has_edge}", flush=True)
    backtest = sequential_backtest(candidates, fills, outcomes, selected) if has_edge else pd.DataFrame()

    out_dir = PROJECT_ROOT / args.out_dir
    write_outputs(
        out_dir,
        args=args,
        bars=bars,
        levels_by_width=levels_by_width,
        candidates=candidates,
        fills=fills,
        outcomes=outcomes,
        scorecard=scorecard,
        gates=gates,
        selected=selected,
        has_edge=has_edge,
        backtest=backtest,
    )
    charts = [] if args.skip_charts else write_charts(out_dir, scorecard, selected)
    render_report(
        PROJECT_ROOT / "research/ict/mss/REPORT.md",
        bars=bars,
        coverage=coverage_table(bars),
        candidates=candidates,
        scorecard=scorecard,
        gates=gates,
        selected=selected,
        has_edge=has_edge,
        backtest=backtest,
        chart_files=charts,
    )
    print(f"[done] report={PROJECT_ROOT / 'research/ict/mss/REPORT.md'}", flush=True)
    print(f"[done] outputs={out_dir}", flush=True)
    return out_dir


if __name__ == "__main__":
    run(parse_args())
