"""Causal 1m ICT-style sweep -> MSS/displacement -> FVG-limit research.

The study deliberately uses only the OHLC columns returned by the existing
``OKXTradeBarLoader``.  Higher timeframes are resampled from that same 1m
stream, so there is one primary execution clock and no independently fetched
higher-timeframe data.

Mechanical definitions (frozen before the run)
-----------------------------------------------
* Liquidity: first sweep of a causally-confirmed 15m/30m/1h/4h swing high/low.
  A swing uses a symmetric ``width`` window and is available only after all
  right-hand candles have closed.
* Long setup: a first sweep below one or more active higher-timeframe swing
  lows, followed within 60 minutes by a 1m bearish-context MSS.  The MSS must
  close above the prior confirmed micro swing high with a displacement body.
  Short setups mirror this rule.
* FVG: the candle after the displacement creates a three-candle gap.  The long
  limit is the next candle's low (the upper FVG edge); the short limit is its
  high (the lower FVG edge).  The order becomes eligible only on the following
  1m bar.
* Stop: the most extreme price from the liquidity sweep through FVG
  confirmation.  A same-bar TP/SL collision is marked as a stop first.

This is research code, not a live trading implementation.  It writes an audit
trail, parameter sensitivity, a preregistered 2023 discovery / 2024-2026
validation gate, and (only if that gate passes) a one-position chronological
replay.
"""

