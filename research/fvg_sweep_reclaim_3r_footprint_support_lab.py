def profit_factor(x: Iterable[float]) -> float:
    s = pd.to_numeric(pd.Series(list(x)), errors="coerce").dropna()
    if s.empty:
        return float("nan")
    gp = float(s[s > 0].sum())
    gl = float(-s[s <= 0].sum())
    if gl <= 0:
        return float("inf") if gp > 0 else float("nan")
    return gp / gl


def top_winner_share(x: Iterable[float], n: int = 5) -> float:
    s = pd.to_numeric(pd.Series(list(x)), errors="coerce").dropna()
    wins = np.sort(s[s > 0].to_numpy(float))[::-1]
    if wins.size == 0:
        return float("nan")
    total = float(wins.sum())
    return float(wins[:n].sum() / total) if total > 0 else float("nan")


def summarize_returns(s: pd.Series, min_count: int = 0) -> dict[str, Any]:
    x = pd.to_numeric(s, errors="coerce").dropna()
    if x.empty:
        return {
            "count": 0,
            "eligible": False,
            "mean": np.nan,
            "median": np.nan,
            "win_rate": np.nan,
            "profit_factor": np.nan,
            "target_rate": np.nan,
            "stop_rate": np.nan,
            "timeout_rate": np.nan,
            "top5_winner_share": np.nan,
            "p05": np.nan,
            "p25": np.nan,
            "p75": np.nan,
            "p95": np.nan,
        }
    return {
        "count": int(len(x)),
        "eligible": bool(len(x) >= int(min_count)),
        "mean": float(x.mean()),
        "median": float(x.median()),
        "win_rate": float((x > 0).mean()),
        "profit_factor": profit_factor(x),
        "top5_winner_share": top_winner_share(x),
        "p05": float(x.quantile(0.05)),
        "p25": float(x.quantile(0.25)),
        "p75": float(x.quantile(0.75)),
        "p95": float(x.quantile(0.95)),
    }


def load_setups(input_dir: Path, args: argparse.Namespace) -> pd.DataFrame:
    path = input_dir / "02_sweep_new_fvg_setups.csv"
    if not path.exists():
        raise FileNotFoundError(f"missing setups file: {path}")
    df = pd.read_csv(path)
    if df.empty:
        return df
    sides = set(sides_from_arg(args.side))
    df = df[df["side"].astype(str).isin(sides)].copy()
    for c in ["sweep_signal_time", "new_fvg_available_time", "sweep_bar_start", "confirm_bar_start"]:
        if c in df.columns:
            df[c] = pd.to_datetime(df[c], errors="coerce")
    for c in [
        "new_fvg_lower", "new_fvg_upper", "new_fvg_mid", "sweep_low", "sweep_high", "sweep_extreme",
        "htf_fvg_width_pct", "new_fvg_width_pct", "impulse_ret_from_sweep_close", "sig_atr_20_pct", "sig_ret_8",
    ]:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce")
    df = df.dropna(subset=["new_fvg_available_time", "new_fvg_lower", "new_fvg_upper", "side"])
    df = df[pd.to_datetime(df["new_fvg_available_time"]) >= pd.Timestamp(args.start_date)].copy()
    df = df[pd.to_datetime(df["new_fvg_available_time"]) <= pd.Timestamp(args.end_date) + pd.Timedelta(days=1)].copy()
    if bool(args.dedup_setups) and not df.empty:
        before = len(df)
        # Remove duplicate variants created by multiple sweep lookbacks for the same actual setup.
        df["_fvg_lower_r"] = df["new_fvg_lower"].round(6)
        df["_fvg_upper_r"] = df["new_fvg_upper"].round(6)
        df["_sweep_low_r"] = df["sweep_low"].round(6)
        df["_sweep_high_r"] = df["sweep_high"].round(6)
        key = ["side", "new_fvg_available_time", "_fvg_lower_r", "_fvg_upper_r", "_sweep_low_r", "_sweep_high_r"]
        df = df.sort_values(["new_fvg_available_time", "side", "setup_id"]).drop_duplicates(key, keep="first").copy()
        df = df.drop(columns=[c for c in df.columns if c.startswith("_")])
        print(f"[setups] dedup {before:,} -> {len(df):,}", flush=True)
    df = df.sort_values(["new_fvg_available_time", "side", "setup_id"]).reset_index(drop=True)
    return df


