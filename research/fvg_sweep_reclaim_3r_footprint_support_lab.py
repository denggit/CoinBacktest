"""
FVG Sweep Reclaim 3R - Footprint Support Lab
===========================================

This script takes the setups generated by ``fvg_sweep_reclaim_3r_research.py``
and tests a stricter causal entry idea:

    HTF FVG + 15m sweep + displacement + new 15m FVG already exists
    -> wait until 0.2% range bar trades back into the new FVG
    -> require range-footprint evidence that the new FVG is defended
    -> enter on the NEXT range bar open
    -> stop at sweep extreme +/- buffer, target fixed RR

Important causality rule:
    The footprint of the touch bar is only known after that range bar closes.
    Therefore confirmed-footprint entries are placed at the next range bar open,
    not inside the same footprint bar.

This is a filter/replay lab, not a production strategy.
"""
