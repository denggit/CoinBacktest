def _parse_float_list(raw: str) -> list[float]:
    out: list[float] = []
    for part in str(raw).split(","):
        part = part.strip()
        if not part:
            continue
        value = float(part)
        if math.isfinite(value):
            out.append(value)
    return sorted(set(out))


