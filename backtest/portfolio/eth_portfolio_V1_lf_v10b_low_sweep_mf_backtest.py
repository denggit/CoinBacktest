def run_lf_v10b_leg(args: argparse.Namespace) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Run the frozen LF V10B child backtest and return normalized trades."""

    lf_args = _build_lf_args(args)
    mom_cfg = v10a.make_momentum_config(lf_args)
    bear_cfg = v10a.make_bear_config(lf_args)
    bull_cfg = v10a.make_bull_config(lf_args)
    exec_cfg = v10a.make_exec_config(mom_cfg)
    bull_exec_cfg = v10a.bull_to_exec_config(bull_cfg) if lf_args.bull_execution_mode == "own" else exec_cfg

    trade_start = pd.Timestamp(args.start_date)
    load_start = pd.Timestamp(args.warmup_start_date or args.start_date)
    load_start_str = load_start.strftime("%Y-%m-%d")

    print(f"[lf] load 4H {args.symbol} {load_start_str}->{args.end_date}; trade_start={args.start_date}", flush=True)
    base = v10a.load_data(args.symbol, load_start_str, args.end_date, "4H")
    momentum = v10a.build_momentum_features(base, mom_cfg)
    bear = v10a.build_bear_features(base, bear_cfg)
    bull = v10a.build_bull_features(base, bull_cfg)
    micro_ctx = v10a.load_range_footprint_context(lf_args, load_start_str, args.end_date)
    momentum = v10a.apply_momentum_long_not_aligned_block(momentum, micro_ctx, lf_args)
    momentum = v10a.apply_momentum_short_fast_speed_block(momentum, micro_ctx, lf_args)
    features = v10a.select_portfolio_signals(momentum, bear, bull, lf_args)
    features = v10a.apply_micro_context_filter(features, micro_ctx, lf_args)
    features = v10b.add_structural_columns(features, lookback_bars=v10b.V10B_STRUCTURAL_STOP.lookback_bars)
    features = features.loc[trade_start : pd.Timestamp(args.end_date)].copy()

    trades, equity = v10b.run_v10b_backtest(
        features,
        exec_cfg,
        engine_cfgs={"MOMENTUM_V3": exec_cfg, "BEAR_V3_ONLY": exec_cfg, "BULL_RECLAIM_V2": bull_exec_cfg},
        global_risk_scale=lf_args.global_risk_scale,
        args=lf_args,
    )
    trades = v10a.attach_engine_to_trades(trades, features)
    out = pd.DataFrame(trades)
    if out.empty:
        return pd.DataFrame(), equity
    out = out.copy()
    out["strategy_leg"] = LF_LEG
    out["variant_name"] = LF_LEG
    out["entry_time"] = pd.to_datetime(out["entry_time"], errors="coerce")
    out["exit_time"] = pd.to_datetime(out["exit_time"], errors="coerce")
    out["side"] = pd.to_numeric(out.get("side", np.nan), errors="coerce")
    out["return_on_sleeve"] = pd.to_numeric(out.get("return_pct", out.get("pnl", 0.0)), errors="coerce")
    # If a legacy row somehow lacks return_pct, fall back to pnl/capital-before.
    if "return_pct" not in out.columns and {"pnl", "capital"}.issubset(out.columns):
        cap_after = pd.to_numeric(out["capital"], errors="coerce")
        pnl = pd.to_numeric(out["pnl"], errors="coerce")
        out["return_on_sleeve"] = pnl / (cap_after - pnl).replace(0, np.nan)
    out["exit_reason"] = out.get("note", "")
    out = attach_lf_position_metrics(out)
    return out.dropna(subset=["entry_time", "exit_time", "return_on_sleeve"]), equity


def _safe_float(value: object, default: float = float("nan")) -> float:
    try:
        out = float(value)
    except (TypeError, ValueError):
        return default
    return out if math.isfinite(out) else default


def _safe_side_from_row(row: pd.Series, default: int = 1) -> int:
    raw = row.get("side", np.nan)
    side = _safe_float(raw, float("nan"))
    if math.isfinite(side) and side != 0:
        return int(np.sign(side))
    typ = str(row.get("type", "")).upper()
    if "SHORT" in typ:
        return -1
    if "LONG" in typ:
        return 1
    leg = str(row.get("strategy_leg", ""))
    if leg.startswith("MF_LOW_SWEEP"):
        return 1
    return int(default)


def attach_lf_position_metrics(trades: pd.DataFrame) -> pd.DataFrame:
    """Attach actual LF notional/risk metrics from V10B closed trades.

    V10B sizing is risk-budget based, not a fixed notional percentage.  These
    diagnostics translate each closed trade into realized notional exposure
    versus the sleeve equity at entry.  They are portfolio-report fields only
    and do not change LF child-strategy logic.
    """

    if trades.empty:
        return trades
    out = trades.copy()
    cap_after = pd.to_numeric(out.get("capital", np.nan), errors="coerce")
    pnl = pd.to_numeric(out.get("pnl", np.nan), errors="coerce")
    cap_before = (cap_after - pnl).replace(0, np.nan)
    qty = pd.to_numeric(out.get("qty", np.nan), errors="coerce").abs()
    entry = pd.to_numeric(out.get("avg_entry", out.get("first_entry", np.nan)), errors="coerce")
    first_entry = pd.to_numeric(out.get("first_entry", entry), errors="coerce")
    initial_sl = pd.to_numeric(out.get("initial_sl", np.nan), errors="coerce")
    notional = qty * entry
    out["capital_before_trade"] = cap_before
    out["position_notional"] = notional
    out["position_notional_mult"] = notional / cap_before
    out["initial_risk_amount"] = qty * (first_entry - initial_sl).abs()
    out["initial_risk_pct_equity"] = out["initial_risk_amount"] / cap_before
    out["margin_fraction_at_leverage15"] = out["position_notional_mult"] / DEFAULT_LEVERAGE
    return out


def attach_mf_position_metrics(trades: pd.DataFrame, assumed_exposure: float = 1.0) -> pd.DataFrame:
    if trades.empty:
        return trades
    out = trades.copy()
    out["position_notional_mult"] = float(assumed_exposure)
    out["initial_risk_pct_equity"] = np.nan
    out["margin_fraction_at_leverage15"] = float(assumed_exposure) / DEFAULT_LEVERAGE
    return out


